        -SuccessMessage "Strimzi CRD '$requiredCrd' is installed" `
        -FailureMessage "Strimzi CRD '$requiredCrd' is missing. Install the cluster operator first; see infrastructure/kubernetes/kafka/README.md"
}

$operatorAvailable = Get-KubectlJsonPath `
