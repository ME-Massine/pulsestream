# 1. Prerequisite (ADR 0005): the cluster resources below are custom resources,
#    so the Strimzi CRDs and cluster operator must be installed first. Checking
#    this explicitly turns the documented ordering constraint into a real
#    assertion, and turns the otherwise cryptic "no matches for kind Kafka" into
#    a message that names the missing prerequisite.
$installedCrds = Get-KubectlJsonPath `
